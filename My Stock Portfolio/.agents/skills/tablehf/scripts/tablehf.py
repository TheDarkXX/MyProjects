"""
tablehf.py — HyperFrames-Native Storyboard & Media Pre-Flight Ingestion CLI (v1.2.0)
Bridge between /flow (Google Flow Veo 3.1 4s), /hfsdirector, and /cchandoff.

Enforces MEDIA_PREFLIGHT_AROLL_BROLL.md gates & zero-slop execution:
  1. Per-frame QC & Safe Cut Window (qc-frames with Full-Res Bottle Guard)
  2. One-command Winner Promotion (promote: archives old take, moves new, updates manifest & timeline)
  3. Automatic HTML Sync (sync-html: injects canonical tags into index.html)
  4. Per-clip UTF-8 JSON Manifest (qc/manifest.json & assets/broll/qc/*.json)
  5. Folder Hygiene (canonical filenames only in assets/; takes/ & rejected/ isolated)
  6. Zero-Gap Visual Continuity Check (gap-check: 0.00s uncovered gaps)
"""

import os
import re
import sys
import json
import shutil
import subprocess
import argparse
from pathlib import Path

if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding="utf-8")
        sys.stderr.reconfigure(encoding="utf-8")
    except Exception:
        pass

CANONICAL_RE = re.compile(r"^[A-Za-z0-9]+-(?:S|A)\d{2}[a-z]?\.mp4$")


def check_folder_hygiene(project_dir: Path):
    """Verify assets/broll and assets/aroll only contain canonical clip names."""
    broll_dir = project_dir / "assets" / "broll"
    aroll_dir = project_dir / "assets" / "aroll"
    non_canonical = []

    for d in (broll_dir, aroll_dir):
        if not d.exists():
            continue
        for f in sorted(d.glob("*.mp4")):
            if not CANONICAL_RE.match(f.name):
                non_canonical.append(f.relative_to(project_dir).as_posix())

    return non_canonical


def write_tags_file(project_dir: Path, tl: dict):
    """Write Rule 35 <video> tags to scratch/broll_tags.html."""
    scratch_dir = project_dir / "scratch"
    scratch_dir.mkdir(parents=True, exist_ok=True)
    out_path = scratch_dir / "broll_tags.html"

    lines = ["<!-- Generated by /tablehf tags (Rule 35 Clean Track Architecture) -->"]
    for c in tl.get("clips", []):
        cid = c.get("id", "")
        fpath = c.get("file", "")
        start = f"{float(c.get('start', 0)):.2f}"
        dur = f"{float(c.get('duration', 0)):.2f}"
        mstart = f"{float(c.get('media_start', 0)):.2f}"
        trk = int(c.get("track", 1))
        zindex = (trk + 1) * 10
        lines.append(
            f'      <video id="{cid}" class="clip" src="{fpath}" data-start="{start}" data-duration="{dur}" data-media-start="{mstart}" data-track-index="{trk}" data-volume="0" muted playsinline style="position:absolute;left:0;top:0;width:1080px;height:1920px;object-fit:cover;z-index:{zindex}"></video>'
        )

    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out_path


def cmd_qc_frames(args):
    """Extract 2fps contact sheet + full-res frame for bottle text audit."""
    clip_path = Path(args.clip_path).resolve()
    if not clip_path.exists():
        print(f"❌ Clip not found: {clip_path}")
        sys.exit(1)

    out_dir = Path(args.output_dir).resolve() if args.output_dir else clip_path.parent.parent.parent / "scratch" / "qc_frames" / clip_path.stem
    out_dir.mkdir(parents=True, exist_ok=True)

    grid_out = out_dir / f"{clip_path.stem}_grid.jpg"
    full_out = out_dir / f"{clip_path.stem}_full_25s.jpg"

    print(f"🔍 Slicing QC frames for: {clip_path.name}")
    # 2fps contact sheet grid
    cmd_grid = [
        "ffmpeg", "-v", "error", "-y", "-i", str(clip_path),
        "-vf", "fps=2,scale=240:426,tile=4x3",
        "-frames:v", "1", "-q:v", "3", str(grid_out)
    ]
    subprocess.run(cmd_grid)

    # 1080p full-res frame at 2.5s (or specified ss)
    cmd_full = [
        "ffmpeg", "-v", "error", "-y", "-ss", str(args.ss), "-i", str(clip_path),
        "-frames:v", "1", "-q:v", "2", str(full_out)
    ]
    subprocess.run(cmd_full)

    print(f"✅ Contact Sheet (2fps): {grid_out}")
    print(f"✅ Full-Res Frame ({args.ss}s): {full_out}")
    print("\n📋 Mandatory Machine Checklist (Double Recheck):")
    print("   [ ] Brand text: DOCTORBANK (exact spelling, unwarped)")
    print("   [ ] Product text: MAGNESIUM NIGHT PLUS")
    print("   [ ] Formula line: NIGHT FORMULA (FAIL if NIGHT FOR4AU8 or gibberish)")
    print("   [ ] Capsule count: 30 Capsules (FAIL if 20 or mutated)")
    print("   [ ] Artifacts: Zero blinding flare, zero invented pink/gold capsule, zero speed lines")
    print("=" * 64)


def cmd_promote(args):
    """Promote a winner repair/candidate clip to canonical name, archiving the old take."""
    project_dir = Path(args.project_dir).resolve()
    clip_path = Path(args.clip_path).resolve()
    shot_id = args.shot_id.upper().strip()

    if not clip_path.exists():
        print(f"❌ Candidate clip not found: {clip_path}")
        sys.exit(1)

    is_aroll = "-A" in shot_id
    role = "aroll" if is_aroll else "broll"
    target_dir = project_dir / "assets" / role
    takes_dir = project_dir / "scratch" / "takes" / role
    target_dir.mkdir(parents=True, exist_ok=True)
    takes_dir.mkdir(parents=True, exist_ok=True)

    canonical_name = f"{shot_id}.mp4"
    canonical_path = target_dir / canonical_name

    # If canonical already exists, archive it
    if canonical_path.exists():
        # Count existing archived takes
        existing_takes = list(takes_dir.glob(f"{shot_id}-take*.mp4"))
        archive_name = f"{shot_id}-take{len(existing_takes) + 1}_archived.mp4"
        archive_path = takes_dir / archive_name
        shutil.copy2(canonical_path, archive_path)
        print(f"📦 Archived old canonical take -> {archive_path.relative_to(project_dir).as_posix()}")

    # Move or copy candidate to canonical
    if clip_path.resolve() != canonical_path.resolve():
        shutil.copy2(clip_path, canonical_path)
        print(f"🚀 Promoted {clip_path.name} -> {canonical_path.relative_to(project_dir).as_posix()}")

    # Update timeline.json
    tl_path = project_dir / "timeline.json"
    if tl_path.exists():
        with open(tl_path, "r", encoding="utf-8") as f:
            tl = json.load(f)

        updated = False
        for c in tl.get("clips", []):
            if c.get("code") == shot_id or c.get("id") == shot_id.lower().replace("mgn4-", ""):
                c["file"] = f"assets/{role}/{canonical_name}"
                if args.safe_in is not None and args.safe_out is not None:
                    c["safe_window"] = [args.safe_in, args.safe_out]
                if args.media_start is not None:
                    c["media_start"] = args.media_start
                if args.reason:
                    c["chosen_reason"] = args.reason
                c["status"] = "pass"
                updated = True
                break

        if updated:
            with open(tl_path, "w", encoding="utf-8") as f:
                json.dump(tl, f, ensure_ascii=False, indent=2)
            print(f"📝 Updated timeline.json for {shot_id}")

    # Regenerate tags and manifest
    write_tags_file(project_dir, tl if tl_path.exists() else {})
    print("✅ Promotion complete.")


def cmd_sync_html(args):
    """Inject scratch/broll_tags.html into index.html cleanly."""
    project_dir = Path(args.project_dir).resolve()
    html_path = project_dir / "index.html"
    tl_path = project_dir / "timeline.json"

    if not html_path.exists() or not tl_path.exists():
        print(f"❌ Missing index.html or timeline.json in {project_dir}")
        sys.exit(1)

    with open(tl_path, "r", encoding="utf-8") as f:
        tl = json.load(f)

    # Generate tag lines
    tags_path = write_tags_file(project_dir, tl)
    with open(tags_path, "r", encoding="utf-8") as f:
        tag_lines = [l for l in f.read().splitlines() if not l.startswith("<!--")]

    # Read index.html
    html_text = html_path.read_text(encoding="utf-8")

    # Replace <video id="..." class="clip" ...></video>
    pattern = re.compile(r'(\s*<video id="[a-zA-Z0-9]+" class="clip"[^>]*></video>)+', re.MULTILINE)
    match = pattern.search(html_text)

    if match:
        new_tags_block = "\n".join(tag_lines)
        new_html = html_text[:match.start()] + "\n" + new_tags_block + html_text[match.end():]
        html_path.write_text(new_html, encoding="utf-8")
        print(f"✅ Injected {len(tl.get('clips', []))} video clip tags into index.html")
    else:
        print("⚠️ Could not locate existing <video class=\"clip\"> block in index.html, skipping direct replacement.")


def cmd_ingest(args):
    """Scan assets/broll and assets/aroll, verify hygiene, manifest, tags, and timeline.json."""
    project_dir = Path(args.project_dir).resolve()
    if not project_dir.exists():
        print(f"❌ Project directory not found: {project_dir}")
        sys.exit(1)

    print("=" * 64)
    print(f"🎬 /tablehf Pre-Flight Ingest & Audit: {project_dir.name}")
    print("=" * 64)

    broll_dir = project_dir / "assets" / "broll"
    aroll_dir = project_dir / "assets" / "aroll"

    broll_files = sorted(broll_dir.glob("*.mp4")) if broll_dir.exists() else []
    aroll_files = sorted(aroll_dir.glob("*.mp4")) if aroll_dir.exists() else []

    print(f"📂 Active B-roll files in assets/broll/: {len(broll_files)}")
    print(f"📂 Active A-roll files in assets/aroll/: {len(aroll_files)}")

    non_canon = check_folder_hygiene(project_dir)
    if non_canon:
        print(f"❌ FOLDER HYGIENE FAIL: Found {len(non_canon)} non-canonical files in assets/:")
        for nc in non_canon:
            print(f"   - {nc} (must move to scratch/takes/ or scratch/rejected/)")
        sys.exit(1)
    else:
        print("✅ Gate 1 (Folder Hygiene): 100% canonical filenames in assets/broll & assets/aroll.")

    tl_path = project_dir / "timeline.json"
    if not tl_path.exists():
        print("❌ Gate 2 (Machine Contract): timeline.json not found!")
        sys.exit(1)

    with open(tl_path, "r", encoding="utf-8") as f:
        tl = json.load(f)

    clips = tl.get("clips", [])
    missing_files = []
    missing_windows = []
    for c in clips:
        fp = project_dir / c.get("file", "")
        if not fp.exists():
            missing_files.append(c.get("file", ""))
        if "safe_window" not in c or len(c["safe_window"]) != 2:
            missing_windows.append(c.get("id", "unknown"))

    if missing_files:
        print(f"❌ Gate 2 (Missing Clip Files): {missing_files}")
        sys.exit(1)
    if missing_windows:
        print(f"❌ Gate 2 (Missing safe_window): {missing_windows}")
        sys.exit(1)

    print(f"✅ Gate 2 (timeline.json): {len(clips)} clips verified with explicit safe_window & existing files.")

    manifest_path = project_dir / "qc" / "manifest.json"
    broll_qc_dir = broll_dir / "qc"
    qc_jsons = list(broll_qc_dir.glob("*.json")) if broll_qc_dir.exists() else []
    if not manifest_path.exists() or len(qc_jsons) < len(clips):
        print(f"⚠️ Gate 3 (QC Manifest): qc/manifest.json={manifest_path.exists()}, assets/broll/qc/*.json={len(qc_jsons)}/{len(clips)}")
    else:
        print(f"✅ Gate 3 (QC Manifest): qc/manifest.json + {len(qc_jsons)} per-clip JSONs verified.")

    tags_path = write_tags_file(project_dir, tl)
    print(f"✅ Gate 4 (Tag Generation): Wrote {len(clips)} Rule-35 <video> tags -> {tags_path.relative_to(project_dir).as_posix()}")

    cmd_gap_check(args)
    return True


def cmd_gap_check(args):
    """Check visual coverage across timeline to ensure 0 uncovered gaps."""
    project_dir = Path(args.project_dir).resolve()
    tl_path = project_dir / "timeline.json"

    if not tl_path.exists():
        print(f"❌ timeline.json not found in: {project_dir}")
        sys.exit(1)

    with open(tl_path, "r", encoding="utf-8") as f:
        tl = json.load(f)

    stages = tl.get("stages", [
        {"id": "s2", "start": 5.9, "end": 10.3},
        {"id": "s4", "start": 17.5, "end": 21.6},
    ])

    intervals = []
    for c in tl.get("clips", []):
        start = float(c["start"])
        dur = float(c["duration"])
        intervals.append((start, start + dur, c.get("id", "clip"), c.get("track", 1)))

    for s in stages:
        intervals.append((float(s["start"]), float(s["end"]), s.get("id", "stage"), 0))

    intervals.sort(key=lambda x: x[0])

    current = 0.0
    gaps = []
    for start, end, cid, trk in intervals:
        if start > current + 0.005:
            gaps.append((current, start))
        current = max(current, end)

    print("-" * 64)
    print(f"📊 Gate 5 (Visual Continuity): {len(intervals)} intervals | 0.00s -> {current:.2f}s")
    if gaps:
        print("❌ GAPS DETECTED:")
        for g in gaps:
            print(f"   ⚠️ Uncovered Interval: {g[0]:.2f}s - {g[1]:.2f}s (Gap: {g[1]-g[0]:.2f}s)")
        sys.exit(1)
    else:
        print("✅ ZERO GAPS: 100% continuous visual coverage across all tracks!")
    print("=" * 64)


def cmd_tags(args):
    """Emit HTML video tags from timeline.json and save to scratch/broll_tags.html."""
    project_dir = Path(args.project_dir).resolve()
    tl_path = project_dir / "timeline.json"

    if not tl_path.exists():
        print(f"❌ timeline.json not found in: {project_dir}")
        sys.exit(1)

    with open(tl_path, "r", encoding="utf-8") as f:
        tl = json.load(f)

    out_path = write_tags_file(project_dir, tl)
    print(out_path.read_text(encoding="utf-8"), end="")


def main():
    parser = argparse.ArgumentParser(description="HyperFrames-Native Storyboard & Pre-Flight Ingestion CLI (v1.2.0)")
    subparsers = parser.add_subparsers(dest="command", help="Subcommand to run")

    # Ingest
    ingest_p = subparsers.add_parser("ingest", help="Audit folder hygiene, QC manifest, timeline.json, tags, and gap-check")
    ingest_p.add_argument("project_dir", nargs="?", default=".", help="Project directory path")

    # Gap check
    gap_p = subparsers.add_parser("gap-check", help="Verify continuous visual coverage")
    gap_p.add_argument("project_dir", nargs="?", default=".", help="Project directory path")

    # Tags
    tags_p = subparsers.add_parser("tags", help="Emit HTML video tags from timeline.json")
    tags_p.add_argument("project_dir", nargs="?", default=".", help="Project directory path")

    # QC frames
    qc_p = subparsers.add_parser("qc-frames", help="Extract 2fps grid and 1080p frame for bottle inspection")
    qc_p.add_argument("clip_path", help="Path to video clip")
    qc_p.add_argument("--output-dir", help="Output directory")
    qc_p.add_argument("--ss", type=float, default=2.5, help="Timestamp for full-res inspection (default: 2.5s)")

    # Promote
    promote_p = subparsers.add_parser("promote", help="Promote repair clip to canonical name & update timeline.json")
    promote_p.add_argument("project_dir", help="Project directory path")
    promote_p.add_argument("shot_id", help="Canonical shot ID (e.g. MGN4-S10 or MGN4-A05)")
    promote_p.add_argument("clip_path", help="Path to candidate/repair video file")
    promote_p.add_argument("--safe-in", type=float, help="Safe start window")
    promote_p.add_argument("--safe-out", type=float, help="Safe end window")
    promote_p.add_argument("--media-start", type=float, help="Media start offset")
    promote_p.add_argument("--reason", help="Reason for promotion and QC verdict")

    # Sync HTML
    sync_p = subparsers.add_parser("sync-html", help="Inject timeline.json tags directly into index.html")
    sync_p.add_argument("project_dir", nargs="?", default=".", help="Project directory path")

    args = parser.parse_args()

    if args.command == "ingest":
        cmd_ingest(args)
    elif args.command == "gap-check":
        cmd_gap_check(args)
    elif args.command == "tags":
        cmd_tags(args)
    elif args.command == "qc-frames":
        cmd_qc_frames(args)
    elif args.command == "promote":
        cmd_promote(args)
    elif args.command == "sync-html":
        cmd_sync_html(args)
    else:
        parser.print_help()


if __name__ == "__main__":
    main()
